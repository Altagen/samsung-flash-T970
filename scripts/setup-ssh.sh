#!/bin/bash
# Install SSH server inside Ubuntu chroot on SM-T970
# Lets Android SSH clients (ConnectBot, JuiceSSH) connect to the chroot,
# avoiding Termux as a daily terminal.
#
# Usage:  ./scripts/setup-ssh.sh
#         ./scripts/setup-ssh.sh --pubkey /path/to/id_ed25519.pub
#
# Requires: Termux + Ubuntu chroot already installed (setup-ubuntu.sh)
#
# Key handling:
# - If ~/.ssh/sm-t970_ed25519 exists, it's reused (idempotent re-runs safe).
# - Otherwise a new ed25519 keypair is generated (no passphrase).
# - To use an existing key of yours, either:
#     a) pass --pubkey /path/to/your_key.pub
#     b) copy beforehand:
#        cp ~/.ssh/id_ed25519     ~/.ssh/sm-t970_ed25519
#        cp ~/.ssh/id_ed25519.pub ~/.ssh/sm-t970_ed25519.pub
#
# Options:
#   --no-connectbot   do not download/install the ConnectBot app

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

KEY_FILE="$HOME/.ssh/sm-t970_ed25519"
KEY_COMMENT="sm-t970-chroot"
SSH_PORT=2222
ENTER_UBUNTU=/data/local/tmp/enter-ubuntu.sh
FWD_PORT=22222      # PC-side port for the self-test (adb forward)
CONNECTBOT_VERSION=11101000   # F-Droid versionCode of ConnectBot 1.11.1
CONNECTBOT_APK="$REPO_ROOT/downloads/connectbot_${CONNECTBOT_VERSION}.apk"
# shellcheck source=lib/fetch.sh
. "$SCRIPT_DIR/lib/fetch.sh"

# Colors
GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'
RED='\033[0;31m'; BOLD='\033[1m'; DIM='\033[2m'; NC='\033[0m'

step() { echo -e "\n${CYAN}${BOLD}[$1]${NC} $2"; }
ok()   { echo -e "  ${GREEN}OK${NC} $1"; }
skip() { echo -e "  ${DIM}SKIP${NC} $1 ${DIM}(already done)${NC}"; }
warn() { echo -e "  ${YELLOW}WARNING${NC} $1"; }
fail() { echo -e "  ${RED}ERROR${NC} $1"; exit 1; }

# --- Parse args ---
PUBKEY_OVERRIDE=""
INSTALL_CONNECTBOT=true
while [ $# -gt 0 ]; do
    case "$1" in
        --pubkey)
            [ -z "${2:-}" ] && fail "--pubkey requires a path argument"
            PUBKEY_OVERRIDE="$2"; shift 2 ;;
        --no-connectbot)
            INSTALL_CONNECTBOT=false; shift ;;
        -h|--help)
            sed -n '2,23p' "$0" | sed 's/^# \?//'; exit 0 ;;
        *) fail "Unknown argument: $1" ;;
    esac
done

echo -e "${BOLD}=== SSH server setup for SM-T970 chroot ===${NC}"

# --- Pre-checks ---
if ! adb devices 2>/dev/null | grep -q "device$"; then
    fail "No device found. Connect the tablet via USB."
fi
if ! adb shell </dev/null 'su -c "test -f /data/ubuntu/bin/bash && echo ok"' 2>/dev/null | grep -q ok; then
    fail "Ubuntu chroot not found. Run setup-ubuntu.sh first."
fi
for tool in ssh ssh-keygen curl; do
    command -v "$tool" >/dev/null 2>&1 || fail "$tool not found on PC (install openssh / curl)."
done
if ! adb shell </dev/null 'su -c "test -x /data/local/tmp/enter-ubuntu.sh && echo ok"' 2>/dev/null | grep -q ok; then
    fail "enter-ubuntu.sh missing on tablet. Re-run setup-ubuntu.sh."
fi

# --- Step 1: SSH keypair ---
step "1/8" "SSH keypair"

mkdir -p "$HOME/.ssh"
chmod 700 "$HOME/.ssh"

if [ -n "$PUBKEY_OVERRIDE" ]; then
    [ -f "$PUBKEY_OVERRIDE" ] || fail "Public key not found: $PUBKEY_OVERRIDE"
    echo "  Using custom public key: $PUBKEY_OVERRIDE"
    PUBKEY_FILE="$PUBKEY_OVERRIDE"
    PRIVKEY_DISPLAY="(your own — not managed by this script)"
elif [ -f "$KEY_FILE" ] && [ -f "$KEY_FILE.pub" ]; then
    skip "Existing keypair at $KEY_FILE"
    echo -e "  ${DIM}Re-run with --pubkey PATH to push a different public key.${NC}"
    PUBKEY_FILE="$KEY_FILE.pub"
    PRIVKEY_DISPLAY="$KEY_FILE"
else
    echo "  Generating ed25519 keypair (no passphrase)..."
    ssh-keygen -t ed25519 -f "$KEY_FILE" -N "" -C "$KEY_COMMENT" -q
    chmod 600 "$KEY_FILE"
    chmod 644 "$KEY_FILE.pub"
    ok "Keypair generated at $KEY_FILE"
    PUBKEY_FILE="$KEY_FILE.pub"
    PRIVKEY_DISPLAY="$KEY_FILE"
fi

# --- Step 2: openssh-server in chroot ---
step "2/8" "openssh-server package"

if adb shell </dev/null 'su -c "test -x /data/ubuntu/usr/sbin/sshd && echo ok"' 2>/dev/null | grep -q ok; then
    skip "openssh-server already installed"
else
    echo "  Installing openssh-server in Ubuntu chroot..."
    echo -e "  ${DIM}This downloads ~5 MB from apt mirrors.${NC}"
    adb shell </dev/null "su -c \"$ENTER_UBUNTU bash -c 'export DEBIAN_FRONTEND=noninteractive; apt update -qq && apt install -y openssh-server'\"" 2>&1 | tail -5
    if ! adb shell </dev/null 'su -c "test -x /data/ubuntu/usr/sbin/sshd && echo ok"' 2>/dev/null | grep -q ok; then
        fail "openssh-server install failed"
    fi
    ok "openssh-server installed"
fi

# --- Step 3: sshd_config ---
step "3/8" "sshd configuration"

TMP_CFG=$(mktemp)
trap 'rm -f "$TMP_CFG"' EXIT

cat > "$TMP_CFG" <<EOF
# Generated by setup-ssh.sh — SM-T970 chroot SSH server
Port $SSH_PORT
ListenAddress 127.0.0.1
# Change to 0.0.0.0 if you want LAN access (reminder: keys-only, root login).

PermitRootLogin yes
PasswordAuthentication no
PubkeyAuthentication yes
UsePAM no
# sshd does not pass its own environment to sessions: set it here so that
# docker / docker-compose reach the native daemon from every SSH session.
SetEnv DOCKER_HOST=unix:///data/docker/docker.sock

X11Forwarding no
PrintMotd no
AcceptEnv LANG LC_*
Subsystem sftp /usr/lib/openssh/sftp-server

SyslogFacility AUTH
LogLevel INFO
EOF

adb push "$TMP_CFG" /sdcard/sshd_config.sm-t970 >/dev/null
adb shell </dev/null 'su -c "
    mkdir -p /data/ubuntu/etc/ssh
    cp /sdcard/sshd_config.sm-t970 /data/ubuntu/etc/ssh/sshd_config
    chmod 644 /data/ubuntu/etc/ssh/sshd_config
    rm /sdcard/sshd_config.sm-t970
"'
ok "sshd_config written (port $SSH_PORT, 127.0.0.1 only, keys only)"

# --- Step 4: authorized_keys + host keys ---
step "4/8" "Authorized keys + host keys"

adb push "$PUBKEY_FILE" /sdcard/authorized_keys.sm-t970 >/dev/null
adb shell </dev/null 'su -c "
    mkdir -p /data/ubuntu/root/.ssh
    chmod 700 /data/ubuntu/root/.ssh
    cp /sdcard/authorized_keys.sm-t970 /data/ubuntu/root/.ssh/authorized_keys
    chmod 600 /data/ubuntu/root/.ssh/authorized_keys
    chown 0:0 /data/ubuntu/root/.ssh /data/ubuntu/root/.ssh/authorized_keys
    rm /sdcard/authorized_keys.sm-t970
"'
ok "Public key installed in /root/.ssh/authorized_keys"

# Host keys — ssh-keygen -A is idempotent (skips existing types)
echo "  Generating missing host keys..."
adb shell </dev/null "su -c \"$ENTER_UBUNTU bash -c 'ssh-keygen -A 2>&1 | tail -3'\"" 2>&1 | tail -3
ok "Host keys ready"

# --- Step 5: Push start scripts ---
step "5/8" "start-ssh scripts"

chmod +x "$SCRIPT_DIR/start-ssh.sh" "$SCRIPT_DIR/start-ssh-inner.sh"
adb push "$SCRIPT_DIR/start-ssh.sh" /data/local/tmp/start-ssh.sh >/dev/null
adb push "$SCRIPT_DIR/start-ssh-inner.sh" /data/local/tmp/start-ssh-inner.sh >/dev/null
adb shell </dev/null 'su -c "chmod +x /data/local/tmp/start-ssh.sh /data/local/tmp/start-ssh-inner.sh"'
ok "Start scripts pushed to /data/local/tmp/"

# --- Step 6: Magisk service.d autostart ---
step "6/8" "Autostart at boot (Magisk service.d)"

chmod +x "$SCRIPT_DIR/magisk-service.d/ssh-boot.sh"
adb push "$SCRIPT_DIR/magisk-service.d/ssh-boot.sh" /sdcard/ssh-boot.sh >/dev/null
adb shell </dev/null 'su -c "
    mkdir -p /data/adb/service.d
    cp /sdcard/ssh-boot.sh /data/adb/service.d/ssh-boot.sh
    chmod +x /data/adb/service.d/ssh-boot.sh
    rm /sdcard/ssh-boot.sh
"'
ok "Autostart enabled (starts once Android has booted and the tablet is unlocked)"

# --- Step 7: Start sshd now + self-test from the PC ---
step "7/8" "Start sshd and test the connection"

# setsid + nohup: sshd must not be tied to this adb session
adb shell </dev/null 'su -c "setsid nohup /data/local/tmp/start-ssh.sh >> /data/local/tmp/ssh-boot.log 2>&1 < /dev/null &"'
LISTENING=false
for _ in $(seq 1 15); do
    # :08AE = port 2222, state 0A = LISTEN (any local address)
    if adb shell </dev/null 'su -c "cat /proc/net/tcp"' 2>/dev/null | grep -qi ':08AE 00000000:0000 0A'; then
        LISTENING=true; break
    fi
    sleep 1
done
$LISTENING || fail "sshd is not listening on 127.0.0.1:$SSH_PORT. See: adb shell su -c 'tail /data/local/tmp/ssh-boot.log'"
ok "sshd listening on 127.0.0.1:$SSH_PORT"

if [ "$PUBKEY_FILE" = "$KEY_FILE.pub" ]; then
    adb forward "tcp:$FWD_PORT" "tcp:$SSH_PORT" >/dev/null
    SELFTEST=$(ssh -i "$KEY_FILE" -p "$FWD_PORT" -o BatchMode=yes -o ConnectTimeout=10 \
        -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR \
        root@127.0.0.1 'echo "$(id -un)@$(. /etc/os-release; echo $PRETTY_NAME) DOCKER_HOST=$DOCKER_HOST"' 2>&1) || true
    adb forward --remove "tcp:$FWD_PORT" >/dev/null 2>&1 || true
    case "$SELFTEST" in
        root@*DOCKER_HOST=unix://*) ok "SSH login works: $SELFTEST" ;;
        *) fail "SSH self-test failed: $SELFTEST" ;;
    esac
else
    echo -e "  ${DIM}Custom key: test it yourself with adb forward tcp:$FWD_PORT tcp:$SSH_PORT${NC}"
fi

# --- Step 8: ConnectBot (Android SSH client) ---
step "8/8" "ConnectBot app"

if ! $INSTALL_CONNECTBOT; then
    skip "ConnectBot (--no-connectbot)"
elif adb shell </dev/null 'pm list packages 2>/dev/null' | grep -q "org.connectbot"; then
    skip "ConnectBot already installed"
else
    fetch_artifact "connectbot_${CONNECTBOT_VERSION}.apk" || fail "ConnectBot APK unavailable"
    adb install "$CONNECTBOT_APK" >/dev/null
    ok "ConnectBot installed"
fi

# --- Done ---
echo ""
echo -e "${GREEN}${BOLD}SSH server setup complete.${NC}"
echo ""
echo -e "${BOLD}sshd is running and restarts at every boot.${NC} Restart it by hand with:"
echo -e "  ${CYAN}adb shell \"su -c 'setsid nohup /data/local/tmp/start-ssh.sh >> /data/local/tmp/ssh-boot.log 2>&1 < /dev/null &'\"${NC}"
echo ""
echo -e "${BOLD}Connect from the PC:${NC}"
echo -e "  ${CYAN}adb forward tcp:$FWD_PORT tcp:$SSH_PORT && ssh -i $KEY_FILE -p $FWD_PORT root@127.0.0.1${NC}"
echo ""
echo -e "${BOLD}Connect from an Android SSH client on the tablet:${NC}"
echo -e "  Host:        ${CYAN}127.0.0.1${NC}"
echo -e "  Port:        ${CYAN}$SSH_PORT${NC}"
echo -e "  Username:    ${CYAN}root${NC}"
echo -e "  Private key: ${CYAN}$PRIVKEY_DISPLAY${NC}"
echo ""
echo -e "${BOLD}Recommended client:${NC} ConnectBot (FOSS, no account, F-Droid + Play Store)"
echo ""
if [ "$PRIVKEY_DISPLAY" != "(your own — not managed by this script)" ]; then
    echo -e "${BOLD}Import the private key into ConnectBot:${NC}"
    echo -e "  1. ${CYAN}adb push $KEY_FILE /sdcard/sm-t970_ed25519${NC}"
    echo "  2. ConnectBot → Menu → Manage Pubkeys → Import → pick the file"
    echo -e "  3. Remove from /sdcard after import: ${CYAN}adb shell rm /sdcard/sm-t970_ed25519${NC}"
    echo "  4. ConnectBot → + → root@127.0.0.1:$SSH_PORT → select the imported key"
fi
echo ""
echo -e "${DIM}To expose sshd on the LAN (e.g. for PC access):${NC}"
echo -e "${DIM}  change ListenAddress in /data/ubuntu/etc/ssh/sshd_config to 0.0.0.0,${NC}"
echo -e "${DIM}  then restart sshd (command above).${NC}"
